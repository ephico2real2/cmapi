#!/usr/bin/env bash
# deploy/mockup-configmap.sh [--check]: writes deploy/manifests/components/portal/00-mockup-configmap.yaml from the built
# mockup mockups/portal/dist/portal.html, as a ConfigMap nginx serves. --check fails when the file is not current (CI).
set -euo pipefail
HERE=$(cd "$(dirname "$0")" && pwd)
SRC="$HERE/../mockups/portal/dist/portal.html"
OUT="$HERE/manifests/components/portal/00-mockup-configmap.yaml"
[ -f "$SRC" ] || { echo "ERROR: $SRC not found; build the mockup first (mockups/portal: node scripts/build-portal.mjs)" >&2; exit 1; }
render() {
  printf '# Generated by deploy/mockup-configmap.sh from mockups/portal/dist/portal.html (sha256 %s). Do not edit.\n' "$(shasum -a 256 "$SRC" | cut -c1-64)"
  printf 'apiVersion: v1\nkind: ConfigMap\nmetadata:\n  name: cmapi-mockup\n  namespace: cmapi\n  labels: {app.kubernetes.io/part-of: cmapi, app.kubernetes.io/component: mockup}\ndata:\n  portal.html: |\n'
  sed 's/^/    /' "$SRC"
}
if [ "${1:-}" = --check ]; then
  diff -q <(render) "$OUT" >/dev/null || { echo "ERROR: $OUT is not current; run deploy/mockup-configmap.sh" >&2; exit 1; }
  echo "mockup ConfigMap is current"
else
  render > "$OUT"; echo "wrote $OUT ($(wc -c <"$OUT" | tr -d ' ') bytes)"
fi
