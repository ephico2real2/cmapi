#!/usr/bin/env bash
# Write issue-register.md: every issue and milestone of the repository, from GitHub, at one read.
# The /agile skill (diagram-kit skill/agile) defines the labels this reads. Usage, from the repository root:
#   scripts/issue-register.sh [owner/repo] [output file]
set -euo pipefail

repo="${1:-ephico2real2/cmapi}"
out="${2:-issue-register.md}"
owner="${repo%%/*}"
name="${repo##*/}"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

# GraphQL, because the REST issue list does not return the sub-issue parent.
# shellcheck disable=SC2016  # $o, $n and $after are GraphQL variables, not shell ones
query='query($o:String!,$n:String!,$after:String){repository(owner:$o,name:$n){issues(first:100,after:$after,orderBy:{field:CREATED_AT,direction:ASC}){
  pageInfo{hasNextPage endCursor}
  nodes{number title state url labels(first:30){nodes{name}} milestone{title} parent{number}}}}}'

after=""
page=0
while :; do
  args=(-f query="$query" -f o="$owner" -f n="$name")
  [[ -n "$after" ]] && args+=(-f after="$after")
  gh api graphql "${args[@]}" > "$tmp/page-$page.json"
  jq -e '.data.repository.issues.nodes' "$tmp/page-$page.json" > /dev/null \
    || { echo "issue-register: GitHub returned no issue list on page $page" >&2; exit 1; }
  [[ "$(jq -r '.data.repository.issues.pageInfo.hasNextPage' "$tmp/page-$page.json")" == "true" ]] || break
  after="$(jq -r '.data.repository.issues.pageInfo.endCursor' "$tmp/page-$page.json")"
  page=$((page + 1))
done
jq -s '[.[].data.repository.issues.nodes[]]' "$tmp"/page-*.json > "$tmp/issues.json"
gh api "repos/$repo/milestones?state=all&per_page=100" > "$tmp/milestones.json"

read_at="$(date -u +%Y-%m-%dT%H:%M:%SZ)"
commit="$(git rev-parse --short HEAD)"

{
  echo "# Issue register"
  echo
  echo "Every issue and milestone of \`$repo\`, read from GitHub at $read_at, at commit \`$commit\`."
  echo "Generated by \`scripts/issue-register.sh\`. Do not edit by hand: run the script again."
  echo "The labels follow the \`/agile\` skill. \"None\" means the issue has no label of that kind yet."
  echo
  echo "## Counts"
  echo
  jq -r '
    def lab($p): [.labels.nodes[].name | select(startswith($p))];
    def work: [.labels.nodes[].name | select(IN("Backlog","In-Progress","Blocked","In-QA","Done"))];
    "| | Count |", "|---|---|",
    "| All issues | \(length) |",
    "| Open | \(map(select(.state == "OPEN")) | length) |",
    "| Closed | \(map(select(.state == "CLOSED")) | length) |",
    (["Backlog","In-Progress","Blocked","In-QA","Done"][] as $w
      | "| Open with work tag \($w) | \(map(select(.state == "OPEN" and (work | index($w)))) | length) |"),
    "| Open without exactly one work tag (must be 0) | \(map(select(.state == "OPEN" and (work | length) != 1)) | length) |",
    "| Open without a status label | \(map(select(.state == "OPEN" and (lab("status:") | length) == 0)) | length) |",
    "| With no parent | \(map(select(.parent == null)) | length) |"
  ' "$tmp/issues.json"
  echo
  echo "## Milestones"
  echo
  if [[ "$(jq length "$tmp/milestones.json")" -eq 0 ]]; then
    echo "None yet."
  else
    jq -r '"| Milestone | State | Due | Open | Closed |", "|---|---|---|---|---|",
      (.[] | "| \(.title) | \(.state) | \(.due_on // "none" | .[0:10]) | \(.open_issues) | \(.closed_issues) |")' "$tmp/milestones.json"
  fi
  echo
  echo "## Issues"
  echo
  jq -r '
    def lab($p): ([.labels.nodes[].name | select(startswith($p)) | ltrimstr($p)] | join(", ")) as $v | if $v == "" then "None" else $v end;
    def pick($set): ([.labels.nodes[].name | select(IN($set[]))] | join(", ")) as $v | if $v == "" then "None" else $v end;
    "| # | Title | Type | State | Work tag | Status | Severity | Class | Parent | Milestone |",
    "|---|---|---|---|---|---|---|---|---|---|",
    (.[] | "| [#\(.number)](\(.url)) | \(.title | gsub("\\|"; "\\\\|")) | \(pick(["epic","feature","story","task","spike","bug"])) | \(.state | ascii_downcase) | \(pick(["Backlog","In-Progress","Blocked","In-QA","Done","Local-Deploy","Sbx-Deploy","Go-Live"])) | \(lab("status:")) | \(lab("sev:")) | \(lab("class:")) | \(if .parent then "#\(.parent.number)" else "None" end) | \(.milestone.title // "None") |")
  ' "$tmp/issues.json"
} > "$out"

echo "issue-register: wrote $out with $(jq length "$tmp/issues.json") issues and $(jq length "$tmp/milestones.json") milestones" >&2
